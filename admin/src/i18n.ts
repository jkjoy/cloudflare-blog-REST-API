const savedLocale = localStorage.getItem('admin_lang');
const locale = ref<Locale>(savedLocale === 'en' ? 'en' : 'zh');

function resolveMessage(path: string): string {
  let value: unknown = messages[locale.value];
  for (const key of path.split('.')) {
    if (!value || typeof value !== 'object') return path;
    value = (value as Record<string, unknown>)[key];
  }
  return typeof value === 'string' ? value : path;
}

export function useAdminI18n() {
  const isChinese = computed(() => locale.value === 'zh');

  function toggleLocale() {
    locale.value = locale.value === 'zh' ? 'en' : 'zh';
    localStorage.setItem('admin_lang', locale.value);
    document.documentElement.lang = locale.value === 'zh' ? 'zh-CN' : 'en';
  }

  return { isChinese, locale, t: resolveMessage, toggleLocale };
}
